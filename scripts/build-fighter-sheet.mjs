import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { buildAttackStrip, buildMoveSheet, buildSilhouetteSheet } from './fighters/sheet.mjs';
import { printReport } from './fighters/verify.mjs';

/**
 * Build one fighter's production move sheet and every review pass with it.
 *
 * Usage: node scripts/build-fighter-sheet.mjs <name>
 *
 * The reviewed artefact is not one image. It is the sheet as it ships, the same
 * sheet with every effect switched off, the bone chain over a flattened figure,
 * the shared floor and pivot with a reach ruler, black silhouettes with the rows
 * deliberately out of button order, and one enlarged strip per attack — plus a
 * frame table and a machine-checked gate that has to pass before any of it is
 * worth a reviewer's time.
 */
const [, , key] = process.argv;
if (key === undefined) {
  console.error('usage: node scripts/build-fighter-sheet.mjs <fighter>');
  process.exit(1);
}

const { FIGHTER } = await import(`./fighters/${key}/fighter.mjs`);

const failures = printReport(FIGHTER);
if (failures > 0) {
  console.error(`\n${String(failures)} gate failure(s) - not exporting.`);
  process.exit(1);
}

const OUT = path.join('docs', 'move-sheets', FIGHTER.key);
await mkdir(OUT, { recursive: true });
const file = (name) => path.join(OUT, `${FIGHTER.key}-${name}`);

// Rows deliberately out of button order for the silhouette test.
const SILHOUETTE_ORDER = [2, 3, 0, 1];

const sheet = await buildMoveSheet(FIGHTER, file('move-sheet.png'), {
  vfx: true,
  subtitle: 'PRODUCTION SHEET  -  EFFECTS ON',
});
console.log(`\nsheet:      ${String(sheet.width)}x${String(sheet.height)}  ${file('move-sheet.png')}`);

await buildMoveSheet(FIGHTER, file('move-sheet-no-vfx.png'), {
  vfx: false,
  subtitle: 'REVIEW PASS  -  EFFECTS OFF, BODY MECHANICS ONLY',
});
console.log(`no-vfx:     ${file('move-sheet-no-vfx.png')}`);

await buildMoveSheet(FIGHTER, file('skeleton-overlay.png'), {
  vfx: false,
  overlay: 'skeleton',
  subtitle: 'REVIEW PASS  -  BONE CHAIN AND CONTACT POINT',
});
console.log(`skeleton:   ${file('skeleton-overlay.png')}`);

await buildMoveSheet(FIGHTER, file('pivot-floor-overlay.png'), {
  vfx: false,
  overlay: 'guides',
  subtitle: 'REVIEW PASS  -  SHARED FLOOR, PIVOT COLUMN, REACH RULER',
});
console.log(`guides:     ${file('pivot-floor-overlay.png')}`);

await buildSilhouetteSheet(FIGHTER, file('silhouettes.png'), SILHOUETTE_ORDER);
console.log(`silhouette: ${file('silhouettes.png')}`);

for (const move of FIGHTER.moves) {
  const slug = `${move.button.toLowerCase()}-${move.name.toLowerCase().replaceAll(' ', '-')}.png`;
  await buildAttackStrip(FIGHTER, file(slug), move, { vfx: true });
  console.log(`strip:      ${file(slug)}`);
}

const rows = FIGHTER.moves.map((move) => {
  const d = move.frameData;
  return `| ${move.button} | ${move.name} | ${move.limb} | ${move.limbClass} | ${move.level} | ${String(d.startup)} | ${String(d.active)} | ${String(d.recovery)} | ${String(d.startup + d.active + d.recovery)} | ${move.purpose.toLowerCase()} |`;
}).join('\n');

const panels = FIGHTER.moves.map((move) => {
  const list = move.panels
    .map((panel) => `| F${String(panel.frame).padStart(2, '0')} | ${panel.phase} | ${panel.label.toLowerCase()} |`)
    .join('\n');
  return `### ${move.button} — ${move.name}\n\n| game frame | phase | panel |\n|---|---|---|\n${list}\n`;
}).join('\n');

await writeFile(path.join(OUT, 'README.md'), `# ${FIGHTER.name} — production move sheet

Generated by \`node scripts/build-fighter-sheet.mjs ${FIGHTER.key}\` from the
shared fighter rig (\`scripts/fighters/\`): one bone table, one drawing pass, one
sheet renderer, so the sheet cannot drift from the character.

## Files

| file | purpose |
|---|---|
| \`${FIGHTER.key}-move-sheet.png\` | production sheet, effects on |
| \`${FIGHTER.key}-move-sheet-no-vfx.png\` | identical poses with every effect switched off |
| \`${FIGHTER.key}-skeleton-overlay.png\` | bone chain and contact point over a flattened figure |
| \`${FIGHTER.key}-pivot-floor-overlay.png\` | shared floor, pivot column and a ten-pixel reach ruler |
| \`${FIGHTER.key}-silhouettes.png\` | flat black silhouettes, rows out of button order |

## Frame data

| button | move | contact limb | class | level | startup | active | recovery | total | role |
|---|---|---|---|---|---:|---:|---:|---:|---|
${rows}

## Panels

Every row runs idle → anticipation → startup → active → follow through →
recovery → idle. \`F##\` is the game frame the pose is taken from.

${panels}
## Guarantees checked by \`node scripts/build-fighter-sheet.mjs ${FIGHTER.key}\`

The export refuses to run while any of these fail:

- every bone keeps its exact length in all forty panels;
- the support foot holds one pixel column for a whole row, so the pivot never
  slides, and all four rows share one idle position on the page;
- nothing is drawn below the shared floor line, effects included;
- the free foot never hangs more than the stance depth below the foot carrying
  the weight;
- the active contact of each attack lands to the right of the hips;
- each contact lands inside the pixel band its attack level claims;
- the contact frame owns the row's furthest reach and clears the idle outline by
  at least eight pixels — so no attack can read as a hunch;
- the pelvis travels vertically across the move, so nothing lands weightless;
- at least three startup and three recovery panels per attack;
- no panel repeats its neighbour, no follow-through repeats its active frame,
  and no two attacks share an active pose.
`);
console.log(`doc:        ${path.join(OUT, 'README.md')}`);
