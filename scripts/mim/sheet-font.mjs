const FALLBACK = ['.....', '.....', '.....', '#####', '.....', '.....', '.....'];

export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

/** Width of a string at the given letter spacing, in source pixels. */
export function textWidth(string, spacing = 1) {
  if (string.length === 0) return 0;
  return string.length * (GLYPH_WIDTH + spacing) - spacing;
}

/**
 * Draw a string. Returns the x just past the last glyph, so callers can chain
 * runs of different colours on one line.
 */
export function text(canvas, x, y, string, colour, spacing = 1) {
  let cursor = Math.round(x);
  const top = Math.round(y);
  for (const character of string.toUpperCase()) {
    const rows = GLYPHS[character] ?? FALLBACK;
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      for (let column = 0; column < GLYPH_WIDTH; column += 1) {
        if (rows[row][column] === '#') canvas.set(cursor + column, top + row, colour);
      }
    }
    cursor += GLYPH_WIDTH + spacing;
  }
  return cursor - spacing;
}
