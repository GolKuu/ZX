import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  buildAttackStrip,
  buildMoveSheet,
  buildSilhouetteSheet,
} from './mim/build-move-sheet.mjs';
import { MOVE_SHEET } from './mim/move-sheet-poses.mjs';

/**
 * Build MIM's production move sheet and its two review passes.
 *
 * The reviewed artefact is not one image but four: the sheet as it ships, the
 * same sheet with every effect switched off, black silhouettes with the rows
 * deliberately out of button order, and one enlarged strip per attack.
 */
const OUT = path.join('docs', 'move-sheets', 'mim');
await mkdir(OUT, { recursive: true });

const SILHOUETTE_ORDER = [2, 3, 0, 1];

const sheet = await buildMoveSheet(
  path.join(OUT, 'mim-move-sheet.png'),
  { vfx: true, subtitle: 'PRODUCTION SHEET  -  EFFECTS ON' },
);
console.log(`sheet:      ${String(sheet.width)}x${String(sheet.height)}  ${path.join(OUT, 'mim-move-sheet.png')}`);

await buildMoveSheet(
  path.join(OUT, 'mim-move-sheet-no-vfx.png'),
  { vfx: false, subtitle: 'REVIEW PASS  -  EFFECTS OFF, BODY MECHANICS ONLY' },
);
console.log(`no-vfx:     ${path.join(OUT, 'mim-move-sheet-no-vfx.png')}`);

await buildSilhouetteSheet(path.join(OUT, 'mim-silhouettes.png'), SILHOUETTE_ORDER);
console.log(`silhouette: ${path.join(OUT, 'mim-silhouettes.png')}`);

const slugs = ['j-mask-jab', 'k-back-elbow', 'i-capoeira-kick', 'l-spinning-kick'];
for (const [index, move] of MOVE_SHEET.entries()) {
  const file = path.join(OUT, `mim-${slugs[index]}.png`);
  await buildAttackStrip(file, move, { vfx: true });
  console.log(`strip:      ${file}`);
}

const rows = MOVE_SHEET.map((move) => {
  const data = move.frameData;
  return `| ${move.button} | ${move.name} | ${move.limb} | ${move.limbClass} | ${move.level} | ${String(data.startup)} | ${String(data.active)} | ${String(data.recovery)} | ${String(data.startup + data.active + data.recovery)} | ${move.purpose.toLowerCase()} |`;
}).join('\n');

const panels = MOVE_SHEET.map((move) => {
  const list = move.panels
    .map((panel) => `| F${String(panel.frame).padStart(2, '0')} | ${panel.phase} | ${panel.label.toLowerCase()} |`)
    .join('\n');
  return `### ${move.button} — ${move.name}\n\n| game frame | phase | panel |\n|---|---|---|\n${list}\n`;
}).join('\n');

await writeFile(path.join(OUT, 'README.md'), `# MIM — production move sheet

Generated by \`node scripts/build-mim-move-sheet.mjs\` from the shipping MIM rig
(\`scripts/mim/\`): same bone table, same palette, same drawing code as the
in-game sprites, so the sheet cannot drift from the character.

## Files

| file | purpose |
|---|---|
| \`mim-move-sheet.png\` | production sheet, effects on |
| \`mim-move-sheet-no-vfx.png\` | identical poses with every effect switched off |
| \`mim-silhouettes.png\` | flat black silhouettes, rows out of button order |
| \`mim-j-mask-jab.png\` | J enlarged 3x |
| \`mim-k-back-elbow.png\` | K enlarged 3x |
| \`mim-i-capoeira-kick.png\` | I enlarged 3x |
| \`mim-l-spinning-kick.png\` | L enlarged 3x |

## Frame data

| button | move | contact limb | class | level | startup | active | recovery | total | role |
|---|---|---|---|---|---:|---:|---:|---:|---|
${rows}

## Panels

Every row runs idle → anticipation → startup → active → follow through →
recovery → idle. \`F##\` is the game frame the pose is taken from.

${panels}
## Guarantees checked by \`node scripts/mim/verify-move-sheet.mjs\`

- every bone keeps its exact length in all forty panels;
- the support foot holds one pixel column for a whole row, so the pivot never
  slides;
- nothing is drawn below the shared floor line;
- the active contact of each attack lands to the right of the hips;
- each contact lands inside the pixel band its attack level claims;
- no two attacks share an active pose.
`);
console.log(`doc:        ${path.join(OUT, 'README.md')}`);
